package com.oop.fooddelivery.service;

import com.oop.fooddelivery.model.*;
import com.oop.fooddelivery.repository.*;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.time.LocalDate;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class OrderServiceTest {

    @Mock private OrderRepository orderRepository;
    @Mock private PaymentRepository paymentRepository;
    @Mock private DeliveryRepository deliveryRepository;
    @Mock private FeedbackRepository feedbackRepository;
    @Mock private FeedbackAccessTokenRepository feedbackTokenRepository;
    @Mock private OrderTrackingTokenRepository trackingTokenRepository;

    private OrderService service;

    @BeforeEach
    void setup() {
        service = new OrderService(orderRepository, paymentRepository, deliveryRepository,
                feedbackRepository, feedbackTokenRepository, trackingTokenRepository);
    }

    private Customer customer() {
        Customer c = new Customer("Viva Tester", "viva@example.com", "0771234567",
                "Colombo 05", "Active");
        c.setCustomerId(12L);
        return c;
    }

    private Order draft() {
        Order order = new Order();
        order.setOrderId(8L);
        order.setCustomer(customer());
        order.setRestaurantName("Viva Kitchen");
        order.setOrderDate(LocalDate.of(2026, 11, 8));
        order.setDeliveryAddress("Colombo 05, Sri Lanka");
        order.setStatus(OrderStatus.PENDING);
        order.calculateTotalAmount();
        return order;
    }

    @Test
    void createsDraftOnlyWhenInitiallyPending() {
        Order submitted = draft();
        when(orderRepository.save(any(Order.class))).thenAnswer(a -> a.getArgument(0));

        Order result = service.createAdminOrder(customer(), submitted);

        assertEquals(OrderStatus.PENDING, result.getStatus());
        assertEquals(0.0, result.getTotalAmount());
        assertNull(result.getOrderId()); // Generated by MySQL, not copied from browser.
        verify(orderRepository).save(result);
    }

    @Test
    void rejectsNewOrderStartingAsDelivered() {
        Order submitted = draft();
        submitted.setStatus(OrderStatus.DELIVERED);
        assertThrows(IllegalArgumentException.class,
                () -> service.createAdminOrder(customer(), submitted));
        verifyNoInteractions(orderRepository);
    }

    @Test
    void advancesPendingToPreparing() {
        Order saved = draft();
        FoodItem food = new FoodItem();
        food.setPrice(500.0);
        saved.addOrderItem(new OrderItem(food, 1));
        when(orderRepository.findById(8L)).thenReturn(Optional.of(saved));
        when(orderRepository.save(saved)).thenReturn(saved);
        Order submitted = draft();
        submitted.setStatus(OrderStatus.PREPARING);

        service.updateAdminOrder(8L, customer(), submitted);

        assertEquals(OrderStatus.PREPARING, saved.getStatus());
        verify(orderRepository).save(saved);
    }

    @Test
    void refusesPreparationWhenOrderHasNoItems() {
        Order saved = draft();
        when(orderRepository.findById(8L)).thenReturn(Optional.of(saved));
        Order submitted = draft();
        submitted.setStatus(OrderStatus.PREPARING);

        assertThrows(IllegalStateException.class,
                () -> service.updateAdminOrder(8L, customer(), submitted));
        verify(orderRepository, never()).save(any(Order.class));
    }

    @Test
    void rejectsSkippingFromPendingDirectlyToReady() {
        Order saved = draft();
        when(orderRepository.findById(8L)).thenReturn(Optional.of(saved));
        Order submitted = draft();
        submitted.setStatus(OrderStatus.READY);

        assertThrows(IllegalArgumentException.class,
                () -> service.updateAdminOrder(8L, customer(), submitted));
        assertEquals(OrderStatus.PENDING, saved.getStatus());
        verify(orderRepository, never()).save(any(Order.class));
    }

    @Test
    void rejectsMetadataChangesAfterPayment() {
        Order saved = draft();
        when(orderRepository.findById(8L)).thenReturn(Optional.of(saved));
        when(paymentRepository.existsByOrder_OrderId(8L)).thenReturn(true);
        Order submitted = draft();
        submitted.setDeliveryAddress("Changed delivery address");

        assertThrows(IllegalStateException.class,
                () -> service.updateAdminOrder(8L, customer(), submitted));
        assertEquals("Colombo 05, Sri Lanka", saved.getDeliveryAddress());
    }

    @Test
    void refusesToEditDeliveredOrder() {
        Order saved = draft();
        saved.setStatus(OrderStatus.DELIVERED);
        when(orderRepository.findById(8L)).thenReturn(Optional.of(saved));

        assertThrows(IllegalStateException.class,
                () -> service.updateAdminOrder(8L, customer(), draft()));
    }

    @Test
    void addsItemAndRecalculatesTotal() {
        Order saved = draft();
        Restaurant restaurant = new Restaurant();
        restaurant.setRestaurantName("Viva Kitchen");
        restaurant.setStatus("Active");
        FoodItem food = new FoodItem();
        food.setFoodItemId(31L);
        food.setRestaurant(restaurant);
        food.setAvailability("Available");
        food.setPrice(600.0);
        when(orderRepository.findById(8L)).thenReturn(Optional.of(saved));

        service.addOrderItem(8L, food, 3);

        assertEquals(1, saved.getOrderItems().size());
        assertEquals(1800.0, saved.getTotalAmount());
        verify(orderRepository).save(saved);
    }

    @Test
    void preventsModifyingPaidOrderItems() {
        Order saved = draft();
        when(orderRepository.findById(8L)).thenReturn(Optional.of(saved));
        when(paymentRepository.existsByOrder_OrderId(8L)).thenReturn(true);

        assertThrows(IllegalStateException.class,
                () -> service.addOrderItem(8L, null, 2));
        verify(orderRepository, never()).save(any(Order.class));
    }

    @Test
    void blocksDeletingOrderWithPaymentHistory() {
        Order saved = draft();
        when(orderRepository.findById(8L)).thenReturn(Optional.of(saved));
        when(paymentRepository.existsByOrder_OrderId(8L)).thenReturn(true);

        assertThrows(IllegalStateException.class, () -> service.deleteOrder(8L));
        verify(orderRepository, never()).delete(any(Order.class));
    }

    @Test
    void deletesUnusedPendingDraft() {
        Order saved = draft();
        when(orderRepository.findById(8L)).thenReturn(Optional.of(saved));

        service.deleteOrder(8L);

        verify(orderRepository).delete(saved);
    }
}
